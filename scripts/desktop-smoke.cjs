const electron = require('electron');
const { app, ipcMain } = electron;
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const assert = require('node:assert/strict');
const { createDesktop } = require('../src/desktop');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'claude-desktop-smoke-'));
app.setPath('userData', temp);
app.setName('Claude Account Launcher — teste');
const state = { platform: process.platform, executable: '/Applications/Claude.app', profiles: [{id:'test-personal',name:'Pessoal'}] };
ipcMain.handle('state', () => ({ ok:true, value:state }));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
app.on('window-all-closed', () => {});
app.whenReady().then(async () => {
  let desktop;
  try {
    const launched = [];
    const options = { electron, getProfiles: () => state.profiles, launchProfile: async id => { launched.push(id); }, stateFile: path.join(temp,'window-state.json'), background:true, onError: error => { throw error; } };
    desktop = createDesktop(options);
    await desktop.ready;
    await delay(200);
    assert.equal(desktop.win.isVisible(), false, 'background launch must stay hidden');
    assert.equal(desktop.tray.isDestroyed(), false);
    const folderIcon = await desktop.win.webContents.executeJavaScript(`document.querySelector('button[aria-label="Abrir pasta de Pessoal"] img')?.getAttribute('src')`);
    assert.equal(folderIcon, 'assets/folder.svg');
    let themeUpdates = 0;
    const setImage = desktop.tray.setImage.bind(desktop.tray);
    desktop.tray.setImage = image => { themeUpdates++; setImage(image); };
    const originalTheme = electron.nativeTheme.themeSource;
    electron.nativeTheme.themeSource = electron.nativeTheme.shouldUseDarkColors ? 'light' : 'dark';
    await delay(150);
    assert.ok(themeUpdates > 0, 'tray image must update when the native theme changes');
    electron.nativeTheme.themeSource = originalTheme;
    await delay(100);

    if (process.platform === 'darwin') assert.equal(app.dock.isVisible(), false);
    const footer = await desktop.win.webContents.executeJavaScript(`document.querySelector('footer').textContent`);
    assert.equal(footer, 'Desenvolvido por Harlane Castro');
    desktop.menu.getMenuItemById('test-personal').click();
    await delay(50);
    assert.deepEqual(launched, ['test-personal']);
    assert.equal(desktop.win.isVisible(), false, 'opening a profile from tray must not open launcher');
    state.profiles.push({id:'test-work',name:'Trabalho'});
    desktop.refreshProfiles();
    assert.ok(desktop.menu.getMenuItemById('test-work'));
    state.profiles.splice(0,1);
    desktop.refreshProfiles();
    assert.equal(desktop.menu.getMenuItemById('test-personal'), null);
    desktop.menu.items[0].click();
    await delay(100);
    assert.equal(desktop.win.isVisible(), true);
    const area = electron.screen.getPrimaryDisplay().workArea;
    const width = Math.min(1120,area.width), height = Math.min(690,area.height);
    desktop.win.setSize(width,height);
    await delay(300);
    desktop.win.close();
    assert.equal(desktop.win.isDestroyed(), false, 'close must preserve tray process');
    assert.equal(desktop.win.isVisible(), false);
    const saved = JSON.parse(fs.readFileSync(options.stateFile,'utf8'));
    assert.equal(saved.bounds.width,width);
    assert.equal(saved.bounds.height,height);
    desktop.showWindow();
    assert.deepEqual(desktop.win.getSize(),[width,height]);
    desktop.persist();
    desktop.tray.destroy();
    desktop.win.destroy();
    desktop = createDesktop(options);
    await desktop.ready;
    assert.deepEqual(desktop.win.getSize(),[width,height], 'recreated window must restore persisted size');
    desktop.showWindow();
    await delay(200);
    fs.mkdirSync(path.join(__dirname,'../dist'),{recursive:true});
    fs.writeFileSync(path.join(__dirname,'../dist/preview.png'),(await desktop.win.webContents.capturePage()).toPNG());
    console.log('PASS: hidden start, native tray menu and profile routing, live menu updates, footer, close-to-tray, saved size and window recreation.');
    desktop.tray.destroy(); desktop.win.destroy();
    fs.rmSync(temp,{recursive:true,force:true});
    app.exit(0);
  } catch(error) {
    console.error(error);
    desktop?.tray.destroy(); desktop?.win.destroy();
    fs.rmSync(temp,{recursive:true,force:true});
    app.exit(1);
  }
}).catch(error => { console.error(error); app.exit(1); });
